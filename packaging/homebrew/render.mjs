// Renders the Homebrew formula for a release from checksums.txt.
// Usage: node packaging/homebrew/render.mjs <version> <checksums.txt> > promptshelf.rb
import { readFileSync } from "node:fs";

const [version, sumsFile] = process.argv.slice(2);
if (!version || !sumsFile) {
  console.error("usage: render.mjs <version> <checksums.txt>");
  process.exit(2);
}
const sums = {};
for (const line of readFileSync(sumsFile, "utf8").split("\n")) {
  const [hash, name] = line.trim().split(/\s+/);
  if (hash && name) sums[name.replace(/^\*/, "")] = hash;
}
const base = `https://github.com/ETSoftwareStudio/promptshelf/releases/download/v${version}`;
function asset(triple) {
  const name = `promptshelf-v${version}-${triple}.tar.gz`;
  if (!sums[name]) {
    console.error(`missing checksum for ${name}`);
    process.exit(1);
  }
  return `url "${base}/${name}"\n      sha256 "${sums[name]}"`;
}

process.stdout.write(`# Generated by the PromptShelf release workflow. Do not edit.
class Promptshelf < Formula
  desc "Save, fill and share prompts; installs the shelf command"
  homepage "https://github.com/ETSoftwareStudio/promptshelf"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      ${asset("aarch64-apple-darwin")}
    end
    on_intel do
      ${asset("x86_64-apple-darwin")}
    end
  end

  on_linux do
    on_intel do
      ${asset("x86_64-unknown-linux-musl")}
    end
  end

  def install
    bin.install "shelf", "promptshelf"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/shelf --version")
  end
end
`);
