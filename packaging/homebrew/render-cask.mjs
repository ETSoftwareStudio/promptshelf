// Renders the Homebrew cask for the desktop app from checksums.txt.
// Usage: node packaging/homebrew/render-cask.mjs <version> <checksums.txt> > promptshelf-app.rb
import { readFileSync } from "node:fs";

const [version, sumsFile] = process.argv.slice(2);
if (!version || !sumsFile) {
  console.error("usage: render-cask.mjs <version> <checksums.txt>");
  process.exit(2);
}
const sums = {};
for (const line of readFileSync(sumsFile, "utf8").split("\n")) {
  const [hash, name] = line.trim().split(/\s+/);
  if (hash && name) sums[name.replace(/^\*/, "")] = hash;
}
const dmg = `PromptShelf-v${version}-macos-universal.dmg`;
if (!sums[dmg]) {
  console.error(`missing checksum for ${dmg}`);
  process.exit(1);
}

// The app id below must match "identifier" in app/src-tauri/tauri.conf.json.
process.stdout.write(`# Generated by the PromptShelf release workflow. Do not edit.
cask "promptshelf-app" do
  version "${version}"
  sha256 "${sums[dmg]}"

  url "https://github.com/ETSoftwareStudio/promptshelf/releases/download/v#{version}/PromptShelf-v#{version}-macos-universal.dmg"
  name "PromptShelf"
  desc "Local-first prompt library"
  homepage "https://github.com/ETSoftwareStudio/promptshelf"

  app "PromptShelf.app"

  zap trash: [
    "~/Library/Application Support/studio.etsoftware.promptshelf",
    "~/Library/Caches/studio.etsoftware.promptshelf",
    "~/Library/Preferences/studio.etsoftware.promptshelf.plist",
    "~/Library/WebKit/studio.etsoftware.promptshelf",
  ]

  caveats <<~EOS
    PromptShelf is not signed yet, so macOS blocks it the first time it opens.
    To allow it, open System Settings > Privacy & Security, then click Open Anyway.
  EOS
end
`);
